PST = {
    chess.PAWN: PAWN, chess.KNIGHT: KNIGHT, chess.BISHOP: BISHOP,
    chess.ROOK: ROOK, chess.QUEEN: QUEEN,
}

BISHOP_PAIR_BONUS = 30


def evaluate(board: chess.Board) -> int:
    """Score in centipawns from White's point of view."""
    score = 0
    phase = 0
    bishops = {chess.WHITE: 0, chess.BLACK: 0}
    kings = {}

    for square, piece in board.piece_map().items():
        pt = piece.piece_type
        white = piece.color == chess.WHITE
        if pt == chess.KING:
            kings[piece.color] = square
            continue
        idx = square ^ 56 if white else square  # mirror vertically for Black
        value = PIECE_VALUES[pt] + PST[pt][idx]
        score += value if white else -value
        phase += PHASE_WEIGHTS.get(pt, 0)
        if pt == chess.BISHOP:
            bishops[piece.color] += 1

    phase = min(phase, 24)
    for color, square in kings.items():
        idx = square ^ 56 if color == chess.WHITE else square
        value = (KING_MG[idx] * phase + KING_EG[idx] * (24 - phase)) // 24
        score += value if color == chess.WHITE else -value

    if bishops[chess.WHITE] >= 2:
        score += BISHOP_PAIR_BONUS
    if bishops[chess.BLACK] >= 2:
        score -= BISHOP_PAIR_BONUS

    return score


def evaluate_relative(board: chess.Board) -> int:
    """Score from the point of view of the side to move (for negamax)."""
    s = evaluate(board)
    return s if board.turn == chess.WHITE else -s
